"""
gcode_converter.py

Turns a raster image into G-code sized for this specific plotter
(see xy_gcode_plotter_no_servo.ino):

    bed:          0..275mm (X) x 0..190mm (Y), origin = home corner
    step scale:   80 steps/mm on both axes
    pen control:  M3 = pen down, M5 = pen up (no-op until the servo
                  is mounted, but the codes are emitted regardless
                  so files are ready to go once it is)

Pipeline: grayscale -> blur -> edge/threshold detection -> contour
tracing -> polyline simplification -> scale-to-fit-bed -> G-code.

This module has no GUI and no serial code -- it's the pure image ->
G-code logic, importable from plotter_studio.py (the GUI) or usable
standalone for scripting/testing.
"""

import cv2
import numpy as np
from PIL import Image

# ---- must match xy_gcode_plotter_no_servo.ino ----
BED_MAX_X_MM = 275.0
BED_MAX_Y_MM = 190.0
STEPS_PER_MM = 80.0  # same on both axes on this machine


class ConversionParams:
    def __init__(self):
        self.margin_mm = 10.0
        self.mode = "edges"          # "edges" (Canny) or "threshold" (binarize)
        self.canny_low = 60
        self.canny_high = 150
        self.threshold_value = 128
        self.invert = False
        self.blur_ksize = 3          # odd number, 0/1 = no blur
        self.simplify_epsilon_px = 1.5
        self.min_contour_len_px = 6.0
        self.max_image_dim = 900     # downscale very large images before processing
        self.flip_x = False
        self.flip_y = True           # image row 0 is top; plotter Y grows upward
        self.rotate_90 = False
        self.draw_feed_mm_min = 900.0


class ConversionResult:
    def __init__(self, contours_mm, gcode_lines, stats):
        self.contours_mm = contours_mm   # list of list[(x_mm, y_mm)]
        self.gcode_lines = gcode_lines    # list[str]
        self.stats = stats                # dict


def _load_grayscale(path, max_dim):
    img = Image.open(path).convert("L")
    w, h = img.size
    scale = min(1.0, max_dim / max(w, h))
    if scale < 1.0:
        img = img.resize((max(1, int(w * scale)), max(1, int(h * scale))), Image.LANCZOS)
    return np.array(img)


def _extract_contours(gray, p: ConversionParams):
    work = gray
    if p.invert:
        work = 255 - work

    k = p.blur_ksize
    if k and k >= 3:
        if k % 2 == 0:
            k += 1
        work = cv2.GaussianBlur(work, (k, k), 0)

    if p.mode == "threshold":
        _, binary = cv2.threshold(work, p.threshold_value, 255, cv2.THRESH_BINARY_INV)
        edges = binary
    else:
        edges = cv2.Canny(work, p.canny_low, p.canny_high)

    contours, _ = cv2.findContours(edges, cv2.RETR_LIST, cv2.CHAIN_APPROX_NONE)

    simplified = []
    for c in contours:
        length = cv2.arcLength(c, False)
        if length < p.min_contour_len_px:
            continue
        eps = max(0.1, p.simplify_epsilon_px)
        approx = cv2.approxPolyDP(c, eps, False)
        pts = [(float(pt[0][0]), float(pt[0][1])) for pt in approx]
        if len(pts) >= 2:
            simplified.append(pts)

    return simplified, edges.shape  # shape = (h, w)


def _transform_points(contours_px, img_shape, p: ConversionParams):
    img_h, img_w = img_shape

    if p.rotate_90:
        # (x, y) -> (y, img_h - x); new canvas size is (img_h, img_w)
        contours_px = [[(y, img_h - x) for (x, y) in c] for c in contours_px]
        img_w, img_h = img_h, img_w

    avail_w = BED_MAX_X_MM - 2 * p.margin_mm
    avail_h = BED_MAX_Y_MM - 2 * p.margin_mm
    if avail_w <= 0 or avail_h <= 0:
        raise ValueError("Margin too large for the bed size")

    scale = min(avail_w / img_w, avail_h / img_h)
    draw_w = img_w * scale
    draw_h = img_h * scale
    off_x = p.margin_mm + (avail_w - draw_w) / 2.0
    off_y = p.margin_mm + (avail_h - draw_h) / 2.0

    def to_mm(px, py):
        x = px * scale
        y = py * scale
        if p.flip_x:
            x = draw_w - x
        if p.flip_y:
            y = draw_h - y
        x += off_x
        y += off_y
        x = min(max(x, 0.0), BED_MAX_X_MM)
        y = min(max(y, 0.0), BED_MAX_Y_MM)
        return (round(x, 3), round(y, 3))

    return [[to_mm(px, py) for (px, py) in c] for c in contours_px]


def _build_gcode(contours_mm, p: ConversionParams):
    lines = [
        "; Generated by gcode_converter.py",
        "G21",
        "G90",
        "G28",
    ]

    for c in contours_mm:
        if len(c) < 2:
            continue
        x0, y0 = c[0]
        lines.append(f"G0 X{x0:.3f} Y{y0:.3f}")
        lines.append("M3")
        for (x, y) in c[1:]:
            lines.append(f"G1 X{x:.3f} Y{y:.3f} F{p.draw_feed_mm_min:.0f}")
        lines.append("M5")

    lines.append("M5")
    lines.append("G0 X0.000 Y0.000")
    lines.append("M2")
    return lines


def _estimate_seconds(contours_mm, p: ConversionParams,
                       travel_mm_s=34.7):
    draw_mm_s = (p.draw_feed_mm_min / 60.0)
    total = 0.0
    prev = (0.0, 0.0)
    for c in contours_mm:
        if not c:
            continue
        # travel from wherever we were to the start of this stroke
        dx, dy = c[0][0] - prev[0], c[0][1] - prev[1]
        total += (dx * dx + dy * dy) ** 0.5 / travel_mm_s
        for i in range(1, len(c)):
            dx = c[i][0] - c[i - 1][0]
            dy = c[i][1] - c[i - 1][1]
            total += (dx * dx + dy * dy) ** 0.5 / max(draw_mm_s, 0.1)
        prev = c[-1]
    return total


def convert_image(path, params: ConversionParams) -> ConversionResult:
    gray = _load_grayscale(path, params.max_image_dim)
    contours_px, shape = _extract_contours(gray, params)
    if not contours_px:
        raise ValueError("No edges/contours found -- try lowering thresholds "
                          "or switching mode")
    contours_mm = _transform_points(contours_px, shape, params)
    gcode_lines = _build_gcode(contours_mm, params)

    total_points = sum(len(c) for c in contours_mm)
    stats = {
        "contours": len(contours_mm),
        "points": total_points,
        "gcode_lines": len(gcode_lines),
        "est_seconds": _estimate_seconds(contours_mm, params),
    }
    return ConversionResult(contours_mm, gcode_lines, stats)
